import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../opentail.htm', import.meta.url),'utf8');
const begin=html.indexOf('const OT_NATIVE_NAMES=');
const end=html.indexOf('function otNativeSupported()',begin);
assert(begin>0&&end>begin,'Unified catalog should be included in Studio');
const src=html.slice(begin,end);
const env=vm.createContext({otCoreCaps:{native_effects:[]},otNativeEffect:'rainbow',otEffectFavorites:[]});
vm.runInContext(src,env);
const first=vm.runInContext('otUnifiedChoices()',env);
assert(first.length>=120,'One catalog must contain all 120 1D WLED-compatible names');
assert(new Set(first.map(x=>x.name.toLowerCase())).size===first.length,'No duplicate effect names');
assert(first.some(e=>e.name==='Plasma Sweep'),'OpenTail original effects share the catalog');
assert(first.some(e=>e.name==='Wipe Random'),'WLED names share the same catalog');
assert(first.every(e=>!e.available),'Never pretend effects run when firmware has not advertised them');
vm.runInContext("otCoreCaps.native_effects=['rainbow','color_wipe_random','plasma_sweep']",env);
const available=vm.runInContext('otUnifiedChoices()',env);
assert(available.find(x=>x.name==='Rainbow')?.key==='rainbow','Legacy CORE-only rainbow remains selectable');
assert(first.find(x=>x.name==='Colorloop')?.key==='colorloop','WLED Colorloop must not collide with CORE Rainbow');
assert(available.find(x=>x.name==='Wipe Random')?.available,'Firmware-confirmed WLED-style entry is available');
assert(available.find(x=>x.name==='Plasma Sweep')?.available,'Original OpenTail entry uses same capability model');
assert(!available.find(x=>x.name==='Twinklefox')?.available,'Unimplemented firmware entries remain disabled');
assert(!html.includes('id="ot-native-effect"'),'No second effect-selector dropdown');
assert(html.includes("if(otControllerMode==='core')return otUnifiedEffectLibrary()"),'CORE uses the same Effects entry point');
console.log('Unified effects UI: catalog, names, capabilities, fallback and no duplicate selector PASS');
